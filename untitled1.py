import re

responses = {
    "greeting": (
        "Hello! Welcome to customer support. How can I help you today?",
        ["hi", "hello", "hey", "good morning", "good evening"],
    ),
    "hours": (
        "Our support team is available Monday to Saturday, 9:00 AM to 6:00 PM.",
        ["hours", "timing", "open", "schedule", "when"],
    ),
    "refund": (
        "Refunds are processed within 5–7 business days after your request is approved. Please share your order ID if you need a status check.",
        ["refund", "money back", "return", "cancel"],
    ),
    "shipping": (
        "Standard delivery takes 3–5 business days. Once dispatched, you'll receive a tracking link via email or SMS.",
        ["shipping", "delivery", "track", "order status", "where is my order"],
    ),
    "human": (
        "I can connect you with a human support agent. Please leave your name and issue summary, and someone will reach out shortly.",
        ["agent", "human", "representative", "support person", "talk to someone"],
    ),
    "thanks": (
        "You're very welcome! Let me know if there's anything else I can assist you with.",
        ["thanks", "thank you", "thx", "appreciate"],
    ),
    "bye": (
        "Goodbye! Have a great day.",
        ["bye", "goodbye", "exit", "quit"],
    ),
}

def get_bot_response(user_input: str) -> str:
    cleaned = re.sub(r"[^a-z0-9\s]", "", user_input.lower()).strip()
    if not cleaned:
        return "Please type a message so I can help you."

    for intent, (reply, keywords) in responses.items():
        for kw in keywords:
            # Match whole words or phrases cleanly
            pattern = r"\b" + re.escape(kw) + r"\b"
            if re.search(pattern, cleaned):
                return reply

    return (
        "I'm not sure I understood that. You can ask me about support hours, "
        "refunds, order delivery, or ask to speak with a support agent."
    )

def run_chat():
    print("Customer Support Bot initialized. Type 'quit' or 'exit' to end.\n")
    while True:
        user_msg = input("You: ")
        reply = get_bot_response(user_msg)
        print(f"Bot: {reply}\n")
        if re.search(r"\b(bye|goodbye|exit|quit)\b", user_msg.lower()):
            break

if __name__ == "__main__":
    run_chat()